#!/usr/bin/env node
'use strict';
/**
 * Writes docs/dianjiangtai/release/content-review.md: the review sheet for the 120-general roster (contentVersion 2) and every
 * player-visible narrative string (spec H8, AC 59, D8). Read-only on the game; the only file written is the sheet.
 *
 *   node docs/dianjiangtai/release/tools/gen-content-review.js
 *
 * The sheet lists every general with stats, tier, blurb, statNote and source, runs the automated checks (forbidden terms from
 * AC 7/50, blurb length, no internal shorthand in player-visible text, sensitive-word advisory list), and leaves a "人工复核"
 * column empty for a human reviewer. Exit code 1 when a hard check fails (the sheet is still written).
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', '..', '..', '..');
const GAME = path.join(ROOT, 'apps', 'dianjiangtai', 'game');
const content = require(path.join(GAME, 'core', 'content', 'generals.v2.js'));
const OUT = path.join(__dirname, '..', 'content-review.md');

const FACTION = { wei: '魏', shu: '蜀', wu: '吴', qun: '群', jin: '晋' };
const ERA = { huangjin: '黄巾', qunxiong: '群雄', chibi: '赤壁', sanfen: '三分', guijin: '归晋' };
const TIER = { jia: '甲', yi: '乙', bing: '丙' };
const FORBIDDEN = ['82-0', 'NBA', '武力', '统率', '政治', '魅力', 'SSR', '抽卡', '传说', '稀有', '三国志', '三国杀', '光荣', 'Koei'];
// advisory only (historical vocabulary that a reviewer should read in context); not a failure
const SENSITIVE = ['夷', '蛮', '贼', '妖', '逆', '奸', '降', '懦', '愚', '蠢', '废', '杀', '屠', '淫', '狗', '猪', '胡', '虏', '寇', '叛', '鲜卑', '匈奴', '乌桓', '羌', '氐'];
// developer shorthand that must never reach a player: era codes, decision ids, design notes
const SHORTHAND = /\b(HJ|QX|CB|SF|GJ)\b|PO-\d|原为简化|(^|；)(增|改为)/;

const g = content.generals;
const esc = (s) => String(s).replace(/\|/g, '\\|');
const apps = (x) => x.appearances.map((a) => FACTION[a.faction] + ':' + a.eras.map((e) => ERA[e]).join('/') + (a.note ? '(' + a.note + ')' : '')).join(' ; ');

const findings = [];
const shorthand = [];
const advisories = [];
g.forEach((x) => {
  const shown = [x.name, x.courtesy, x.blurb, x.statNote].join('|');
  FORBIDDEN.forEach((f) => { if (shown.includes(f)) findings.push(x.id + ' contains forbidden term ' + f); });
  if ([...x.blurb].length > 14) findings.push(x.id + ' blurb longer than 14 characters');
  if (!x.statNote || !x.source) findings.push(x.id + ' missing statNote or source');
  if (x.portraitId !== null) findings.push(x.id + ' portraitId is not null');
  if (SHORTHAND.test(x.blurb + '|' + x.statNote)) shorthand.push(x);
  const hits = SENSITIVE.filter((s) => (x.blurb + '|' + x.statNote).includes(s));
  if (hits.length) advisories.push([x, hits]);
});

const lines = [];
const L = (s) => lines.push(s === undefined ? '' : s);
L('# 点将台: content review sheet (contentVersion ' + content.contentVersion + ', ' + g.length + ' generals)');
L();
L('Generated by `docs/dianjiangtai/release/tools/gen-content-review.js` from `apps/dianjiangtai/game/core/content/generals.v2.js` at build `3df1b89333d8d05b1d008ce57bfd29b2d1f46452` (the code is identical to 6582873). Do not edit by hand: re-run the script. It satisfies the spec H8 / AC 59 requirement that release reviews the 临阵生变 template list and the roster `statNote`s before submission (the review result is in `rules-check.md` §1.11). The "人工复核" column is for a human reader (OK / FIX / DROP); nothing in the spec requires it, it is recommended (HANDOFF section 1).');
L();
L('## 1. Automated checks');
L();
L('| Check | Result |');
L('|---|---|');
L('| Forbidden terms (AC 7, AC 50: 82-0, NBA, 武力, 统率, 政治, 魅力, SSR, 抽卡, 传说, 稀有, 三国志, 三国杀, 光荣, Koei) in name, courtesy name, blurb, statNote | ' + (findings.some((f) => f.includes('forbidden')) ? 'FAIL' : 'PASS: none') + ' |');
L('| `blurb` at most 14 characters | ' + (findings.some((f) => f.includes('blurb')) ? 'FAIL' : 'PASS') + ' |');
L('| No internal shorthand in player-visible text (era codes HJ/QX/CB/SF/GJ, decision ids such as PO-3, design notes such as 原为简化); the statNote is drawn in the detail sheet (`js/render/draft.js`) | ' + (shorthand.length ? '**FAIL: ' + shorthand.length + ' generals, see section 1a**' : 'PASS') + ' |');
L('| every general has `statNote` and `source`; `portraitId` is null (no portrait image, CTO-D1) | ' + (findings.some((f) => /missing|portraitId/.test(f)) ? 'FAIL' : 'PASS') + ' |');
L('| Roster size / primary factions | ' + g.length + ' generals; ' + ['shu', 'wei', 'wu', 'qun', 'jin'].map((f) => FACTION[f] + ' ' + g.filter((x) => x.faction === f).length).join(' · ') + ' |');
L('| Tiers | ' + ['jia', 'yi', 'bing'].map((t) => TIER[t] + ' ' + g.filter((x) => x.tier === t).length).join(' · ') + ' |');
L('| `statNote`/`blurb` text containing historical vocabulary a reader may want to see in context (advisory, not a failure) | ' + advisories.length + ' generals, listed in section 4 |');
if (findings.length) { L(); findings.forEach((f) => L('- FINDING: ' + f)); }
L();
if (!shorthand.length) {
  L('### 1a. statNote rewrites: done (TD-10, QA V1-1 closed)');
  L();
  L('The ten statNotes that carried developer shorthand (赵云, 马超, 黄忠, 姜维, 张郃, 夏侯惇, 张辽, 司马懿, 邓艾, 吕布) were rewritten as short neutral historical notes (TD-10; QA re-check verified the eras). 孟获 now reads 南中各族所服 (the advisory is closed). Stats are unchanged and contentVersion was not bumped (text-only edits), so the seed bank is unaffected. The text below is the final text to sign off.');
  L();
}
if (shorthand.length) {
  L('### 1a. statNotes with internal shorthand (ACTION for the CTO / product-ux: rewrite in plain Chinese; stats unchanged)');
  L();
  L('The detail sheet shows the statNote to players (`maxLines` 2, or 4 in large-text mode), so these fragments can reach the screen.');
  L();
  L('| 将 | statNote as shipped | what to fix |');
  L('|---|---|---|');
  shorthand.forEach((x) => L('| ' + x.name + ' | ' + esc(x.statNote) + ' | ' + '`' + (x.blurb + '|' + x.statNote).match(SHORTHAND)[0].replace(/^；/, '') + '` (internal code, id, change-log verb or design note) |'));
  L();
}
L('## 2. Narrative strings shown to players (texts)');
L();
const t = content.texts;
L('| Group | Strings |');
L('|---|---|');
const flat = (o) => (typeof o === 'string' ? [o] : Array.isArray(o) ? o : Object.keys(o).flatMap((k) => flat(o[k]).map((v) => k + ': ' + v)));
Object.keys(t).forEach((k) => L('| `' + k + '` | ' + esc(flat(t[k]).join(' / ')) + ' |'));
L();
L('The 临阵生变 lines are the four `wavering` templates (AC 59): each is neutral ("阵脚动摇", "军心不稳", "战机贻误", "前军失序"), none names a person except through `{name}`, none insults. They fire only for generals whose 信 is 3 or lower (section 3).');
L();
L('## 3. Generals who can trigger 临阵生变 (信 <= 3) and the notes players can read');
L();
L('| 将 | 信 | blurb | statNote |');
L('|---|---|---|---|');
g.filter((x) => x.stats.xin <= 3).forEach((x) => L('| ' + x.name + ' | ' + x.stats.xin + ' | ' + esc(x.blurb) + ' | ' + esc(x.statNote) + ' |'));
L();
L('## 4. Advisory: historical vocabulary to read in context');
L();
L('| 将 | words found | blurb | statNote | recommendation |');
L('|---|---|---|---|---|');
const REC = {
  g_menghuo: 'Done: the note now reads "南中各族所服" (the period term 夷汉 is gone; PO-4 keeps 孟获 as the one minority-region figure). No contentVersion bump (text only).',
  g_ganning: 'Low: "仁4：粗猛好杀" is a sourced character note, not mockery; acceptable, optionally soften to "粗猛".',
  g_dongzhuo: 'Low: sourced and neutral in tone ("暴虐失众"); the 临阵生变 template applies to him.',
  g_sunhao: 'Low: "用刑酷烈（本传）" cites the record.',
};
advisories.forEach(([x, hits]) => L('| ' + x.name + ' | ' + hits.join(' ') + ' | ' + esc(x.blurb) + ' | ' + esc(x.statNote) + ' | ' + (REC[x.id] || 'OK: historical event or record wording, no judgement of a people or person beyond the cited fact') + ' |'));
L();
L('## 5. Full roster');
L();
L('`statNote` is shown in the general detail sheet (not on 识人 days before the verdict); `source` is internal. 五德 order: 智 信 仁 勇 严.');
L();
L('| # | 将 (字) | 主阵营 | 出场 (阵营:时代) | 智 | 信 | 仁 | 勇 | 严 | 级 | blurb | statNote | source | 人工复核 |');
L('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
g.forEach((x, i) => L('| ' + (i + 1) + ' | ' + x.name + (x.courtesy ? ' (' + x.courtesy + ')' : '') + ' | ' + FACTION[x.faction] + ' | ' + esc(apps(x)) + ' | ' + ['zhi', 'xin', 'ren', 'yong', 'yan'].map((k) => x.stats[k]).join(' | ') + ' | ' + TIER[x.tier] + ' | ' + esc(x.blurb) + ' | ' + esc(x.statNote) + ' | ' + esc(x.source) + ' |  |'));
L();
L('## 6. Bonds (羁绊)');
L();
L('| 名 | 成员 | 加成 |');
L('|---|---|---|');
const nameOf = Object.fromEntries(g.map((x) => [x.id, x.name]));
content.bonds.forEach((b) => L('| ' + b.label + ' | ' + b.members.map((m) => nameOf[m] || m).join('、') + ' | +' + b.bonus + ' |'));
L();
fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log('wrote', path.relative(ROOT, OUT), '(' + g.length + ' generals, ' + findings.length + ' findings, ' + shorthand.length + ' with internal shorthand, ' + advisories.length + ' advisories)');
process.exit(findings.length || shorthand.length ? 1 : 0);
