const { boot, answer, events, count, dailyLookup, startUp, closeHowto, rights, miss } = require('./helpers');

test('free play: one 再答一次 per run through the rewarded stub, the missed question does not count (AC 36, 41)', async (t) => {
  const g = await startUp(t, { privacy: { state: 'agreed', scope: true } });
  await closeHowto(g);
  g.tapId('home:free');
  let v = g.view();
  assert.strictEqual(v.vm.mode, 'free');
  assert.strictEqual(v.vm.headerText, '随便比比 · 全部');
  assert.strictEqual(v.vm.deckLength, 60);
  assert.strictEqual(v.vm.ranked, false);
  await rights(g, 3);
  assert.strictEqual(g.view().vm.streak, 3);
  const missedK = g.view().vm.k;
  assert.strictEqual(missedK, 4);
  const lastBottom = g.app.ctl.state.r.q.bottom.factId;
  await miss(g);
  v = g.view();
  assert.strictEqual(v.screen, 'play');
  assert.strictEqual(v.vm.sheet, 'continue');
  assert.ok(/^差一点！/.test(v.vm.sheetVm.missText));
  assert.strictEqual(count(g, 'continue_offer'), 1);
  assert.strictEqual(g.log.ads.length, 0, 'nothing is requested before the tap');
  g.tapId('continue:video');
  await g.settle();
  assert.ok(g.app.ads.overlay, 'stub overlay shown');
  g.wait(3100);
  g.tapId('adstub:complete');
  await g.settle();
  v = g.view();
  assert.strictEqual(v.vm.sheet, null);
  assert.strictEqual(v.vm.phase, 'awaitAnswer');
  assert.strictEqual(v.vm.k, missedK + 1, 'continues with the next question');
  assert.strictEqual(v.vm.streak, 3, 'the missed question does not count');
  assert.strictEqual(v.vm.lifeUsed, true);
  const q = g.app.ctl.state.r.q;
  if (!q.segmentStart) assert.strictEqual(q.top.factId, lastBottom, 'the missed bottom card becomes the top card');
  await rights(g, 2);
  assert.strictEqual(g.view().vm.streak, 5);
  await miss(g);
  v = g.view();
  assert.strictEqual(v.screen, 'result', 'a second miss ends the run with no offer');
  assert.strictEqual(count(g, 'continue_offer'), 1);
  assert.strictEqual(v.vm.streak, 5);
  assert.strictEqual(v.vm.streakText, '5（含再答一次）');
  assert.strictEqual(v.vm.ranked, false);
  assert.ok(v.vm.miss && v.vm.miss.top.valueText);
  assert.strictEqual(g.log.cloudWrites.length, 0, 'free results never write the board marker');
  // best-effort submit: the server replays it and agrees
  await g.settle();
  const runs = Object.values(g.app.api.mock.db.runs);
  assert.strictEqual(runs.length, 1);
  assert.strictEqual(runs[0].serverStreak, 5);
  assert.strictEqual(runs[0].mismatch, false);
  assert.strictEqual(runs[0].lifeUsed, true);
  const ev = events(g).filter((e) => e.name === 'continue_result');
  assert.deepStrictEqual(ev.map((e) => e.props.result), ['completed']);
  assert.strictEqual(count(g, 'ad_reward'), 1);
  assert.strictEqual(g.app.store.state.bestFree, 5);
});

test('再答一次: closing early ends the run, no-fill grants once, declining ends the run (AC 42)', async (t) => {
  const g = await startUp(t);
  await closeHowto(g);
  g.tapId('home:free');
  await rights(g, 2);
  await miss(g);
  g.tapId('continue:video');
  await g.settle();
  g.tapId('adstub:skip');
  await g.settle();
  let v = g.view();
  assert.strictEqual(v.screen, 'result');
  assert.strictEqual(v.vm.streak, 2);
  assert.strictEqual(v.vm.streakText, '2');
  assert.ok(events(g).some((e) => e.name === 'continue_result' && e.props.result === 'closedEarly'));
  assert.strictEqual(count(g, 'ad_close_early'), 1);
  // no fill: free once, with the toast
  g.app.ads.stubSim.rewardedError = 1004;
  g.tapId('result:again');
  await rights(g, 1);
  await miss(g);
  g.tapId('continue:video');
  await g.settle();
  v = g.view();
  assert.strictEqual(v.screen, 'play');
  assert.strictEqual(v.vm.phase, 'awaitAnswer');
  assert.strictEqual(v.vm.lifeUsed, true);
  assert.strictEqual(g.app.ctl.state.ui.toast.text, '暂无广告，本次免费');
  assert.ok(events(g).some((e) => e.name === 'continue_result' && e.props.result === 'noFillGrant'));
  await miss(g);
  v = g.view();
  assert.strictEqual(v.screen, 'result', 'the life is used up');
  // declined with 看结果
  g.app.ads.stubSim.rewardedError = null;
  g.tapId('result:again');
  await rights(g, 1);
  await miss(g);
  g.tapId('continue:result');
  await g.settle();
  v = g.view();
  assert.strictEqual(v.screen, 'result');
  assert.strictEqual(v.vm.streak, 1);
  assert.ok(events(g).some((e) => e.name === 'continue_result' && e.props.result === 'declined'));
});

test('free play: 返回 asks first and logs run_abandon; the daily keeps its attempt (AC 8)', async (t) => {
  const g = await startUp(t);
  await closeHowto(g);
  g.tapId('home:free');
  await rights(g, 1);
  g.tapId('back');
  assert.strictEqual(g.view().overlay.dialog.text, '结束本局？');
  g.tapId('dialog:cancel');
  assert.strictEqual(g.view().screen, 'play');
  g.tapId('back');
  g.tapId('dialog:confirm');
  assert.strictEqual(g.view().screen, 'home');
  assert.strictEqual(count(g, 'run_abandon'), 1);
  g.tapId('home:daily');
  await g.settle();
  await rights(g, 2, dailyLookup(g));
  g.tapId('back');
  assert.strictEqual(g.view().overlay.dialog.text, '进度会保留，可稍后继续');
  g.tapId('dialog:confirm');
  await g.settle();
  const hv = g.view().vm;
  assert.strictEqual(hv.daily.state, 'inProgress');
  assert.strictEqual(hv.daily.progressText, '已连对 2 · 第 3 题');
  assert.strictEqual(count(g, 'run_abandon'), 1, 'no abandon event for the daily');
  g.tapId('home:daily');
  await g.settle();
  assert.strictEqual(g.view().vm.k, 3);
  assert.strictEqual(g.view().vm.streak, 2);
});

test('free play: the category picker filters decks and persists (AC 37, 40)', async (t) => {
  const g = await startUp(t);
  await closeHowto(g);
  g.tapId('home:category');
  const sv = g.view().vm.sheetVm;
  assert.deepStrictEqual(sv.options.map((o) => o.key), ['all', 'city', 'animal', 'dist'], 'only categories with enough free facts are offered');
  assert.ok(sv.options.every((o) => o.factCount > 0));
  g.tapId('category:animal');
  assert.strictEqual(g.view().vm.sheet, null);
  assert.strictEqual(g.view().vm.free.categoryLabel, '动物');
  assert.strictEqual(count(g, 'category_select'), 1);
  g.tapId('home:free');
  assert.strictEqual(g.view().vm.headerText, '随便比比 · 动物');
  const r = g.app.ctl.state.r;
  r.deck.questions.forEach((qq) => assert.ok(['animal_weight', 'animal_life'].includes(qq.m)));
  await rights(g, 1);
  await miss(g);
  g.tapId('continue:result');
  await g.settle();
  g.tapId('result:again');
  assert.strictEqual(g.view().vm.headerText, '随便比比 · 动物', '再来一局 uses the last category');
  const g2 = boot(t, { storage: g.storage });
  await g2.settle();
  assert.strictEqual(g2.view().vm.free.categoryLabel, '动物', 'the choice persists');
});

