test('free play works in airplane mode, the result is shown and the submit waits (AC 36)', async (t) => {
  const g = await startUp(t);
  await closeHowto(g);
  g.app.api.mock.offline = true;
  await g.app.ctl.start({ scene: 1001, query: {} }); // a cold start without a network
  await g.settle();
  const hv = g.view().vm;
  assert.strictEqual(hv.daily.state, 'offline');
  assert.ok(g.has('home:retry'));
  g.tapId('home:free');
  await rights(g, 2);
  await miss(g);
  g.tapId('continue:result');
  await g.settle();
  const v = g.view();
  assert.strictEqual(v.screen, 'result');
  assert.strictEqual(v.vm.streak, 2);
  assert.strictEqual(g.app.store.state.pendingSubmits.length, 1, 'the submit is queued best-effort');
  assert.strictEqual(Object.keys(g.app.api.mock.db.runs).length, 0);
  // online again: the next onShow sends it
  g.app.api.mock.offline = false;
  g.show({ scene: 1001, query: {} });
  await g.settle();
  assert.strictEqual(g.app.store.state.pendingSubmits.length, 0);
  assert.strictEqual(Object.values(g.app.api.mock.db.runs)[0].serverStreak, 2);
  g.tapId('result:back');
  g.tapId('home:retry');
  await g.settle();
  assert.strictEqual(g.view().vm.daily.state, 'available');
});

