  async function loadAlbum(more) {
    const a = c.album;
    if (!more) {
      a.state = 'loading';
      invalidate();
    }
    const r = await api.getMyChains(more ? { cursor: a.cursor } : {});
    if (c.album !== a) return;
    if (r && r.ok) {
      noteServerTime(r);
      const rows = r.items.map((it) => V.albumRow(it, serverNow()));
      a.items = more ? a.items.concat(rows) : rows;
      a.cursor = r.cursor || null;
      a.streak = r.streak || 0;
      a.streakText = allowance.streakText(a.streak);
      a.state = a.items.length ? 'ready' : 'empty';
      a.cached = false;
      if (!more) cacheAlbum();
    } else if (!more && isNet(r) && S.albumCache && S.albumCache.items.length) {
      a.items = S.albumCache.items; // offline: the last list, read-only
      a.cursor = null;
      a.streakText = S.albumCache.streakText;
      a.state = 'offline';
      a.cached = true;
    } else if (isNet(r)) a.state = more ? a.state : 'error'; // no cached list to show read-only: the error state, which offers 重试 (AC 109)
    else {
      a.state = more ? a.state : 'error';
      if (!more) track('error', { where: 'getMyChains', code: r ? r.code : 'none' });
    }
    track('album_view', { state: a.state, counts: a.items.length });
    invalidate();
  }

