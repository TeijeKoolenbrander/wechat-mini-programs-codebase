'use strict';
// Regenerates core/vocab.js (the FIXTURE vocabulary) from the mock fixture: starters first, then group words.
// The real vocab.js is produced by tools/pipeline (spec 3.2) and replaces this file.
// Usage: node tools/gen-fixture-vocab.js
const fs = require('node:fs');
const path = require('node:path');
const { GROUPS, CLOSE, DAILY_BANK, PRACTICE_BANK } = require('../js/dev/mock-fixture');
const { STARTERS } = require('../core/starters');

const seen = new Set();
const words = [];
const add = (w) => {
  if (!seen.has(w)) {
    seen.add(w);
    words.push(w);
  }
};
STARTERS.forEach(add);
DAILY_BANK.concat(PRACTICE_BANK).forEach(add);
Object.keys(GROUPS).forEach((g) => GROUPS[g].forEach(add));
Object.keys(CLOSE).forEach((a) => CLOSE[a].forEach(add));

const out =
  '/**\n * FIXTURE vocabulary (' + words.length + ' words, frequency order; the line number is vocabIdx).\n' +
  ' * Generated by tools/gen-fixture-vocab.js for the offline mock. The pipeline replaces this file with the real\n' +
  ' * vocab.v<N> as `module.exports = "word\\nword..."` (a .js module: mini games cannot require .txt).\n */\n' +
  'module.exports = ' + JSON.stringify(words.join('\n')) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'core', 'vocab.js'), out);
console.log('wrote core/vocab.js with ' + words.length + ' words');
