#!/usr/bin/env node
'use strict';
// Builds / checks the daily schedule (spec 4.2, PD-29, AC 9).
//   node tools/build-schedule.js [--launch YYYYMMDD] [--days 365] [--out core/content/schedule.v1.js]
//   node tools/build-schedule.js --check [--file core/content/schedule.v1.js]   exit 1 on any rule violation
//   node tools/build-schedule.js --capacity                                   how many easy / split items the library has
// The library is core/content/spectra.v1.js + the server-only answer key core/content/anchors.v1.js (content owner;
// the schedule needs the tags). The schedule is deterministic for (library, launch date) and is itself server-only (TD-62).
const fs = require('fs');
const path = require('path');
const { getServerContent: getContent } = require('../core/content');
const { buildSchedule, validateSchedule, capacityReport, MIN_DAYS } = require('../core/schedule');
const { CONFIG } = require('../core/config');

const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : dflt;
};
const defaultFile = path.resolve(__dirname, '..', 'core', 'content', 'schedule.v1.js');

const content = getContent();
if (!content) {
  console.error('core/content/spectra.v1.js or core/content/anchors.v1.js not found: the content owner has not delivered the library yet');
  process.exit(2);
}

if (args.includes('--capacity')) {
  console.log(JSON.stringify(capacityReport(content), null, 2));
  process.exit(0);
}

if (args.includes('--check')) {
  const file = path.resolve(opt('--file', defaultFile));
  const schedule = require(file);
  const errs = validateSchedule(schedule, content);
  if (errs.length) {
    console.error(errs.slice(0, 40).join('\n') + (errs.length > 40 ? '\n... ' + (errs.length - 40) + ' more' : ''));
    process.exit(1);
  }
  console.log('schedule ok: ' + schedule.days.length + ' days from ' + schedule.launchDateKey);
  process.exit(0);
}

const launchKey = opt('--launch', CONFIG.daily.launchDateKey);
const days = Number(opt('--days', MIN_DAYS));
const res = buildSchedule(content, { launchKey, days });
if (!res.ok) {
  console.error('build failed: ' + res.error);
  console.error(JSON.stringify(capacityReport(content)));
  process.exit(1);
}
const errs = validateSchedule(res.schedule, content, { minDays: Math.min(days, MIN_DAYS) });
if (errs.length) {
  console.error('built schedule fails its own check:\n' + errs.slice(0, 20).join('\n'));
  process.exit(1);
}
const out = path.resolve(opt('--out', defaultFile));
const body =
  "'use strict';\n// GENERATED by tools/build-schedule.js (launch " + launchKey + ', ' + days + ' days). Do not edit by hand.\n' +
  'module.exports = ' + JSON.stringify(res.schedule) + ';\n';
fs.writeFileSync(out, body);
console.log('wrote ' + out + ' (' + days + ' days, ' + Buffer.byteLength(body) + ' bytes)');
