#!/usr/bin/env node
/**
 * Builds core/content/schedule.v1.js offline (spec 4.2):
 *   node tools/build-schedule.js [--days 400] [--launch 20261101] [--check]
 * --check only validates the committed schedule (CI).
 */
const fs = require('node:fs');
const path = require('node:path');
const GAME = path.join(__dirname, '..');
const { getContent } = require(path.join(GAME, 'core/content.js'));
const { getConfig } = require(path.join(GAME, 'core/config.js'));
const { buildSchedule, checkSchedule } = require(path.join(GAME, 'core/schedule.js'));

const arg = (name, d) => {
  const i = process.argv.indexOf('--' + name);
  return i >= 0 ? process.argv[i + 1] : d;
};
const content = getContent(1);
const OUT = path.join(GAME, 'core/content/schedule.v1.js');

if (process.argv.includes('--check')) {
  const bad = checkSchedule(content, require(OUT));
  if (bad.length) {
    console.error(bad.join('\n'));
    process.exit(1);
  }
  console.log('schedule ok');
  process.exit(0);
}

const launch = arg('launch', getConfig(1).daily.launchDateKey);
const days = Number(arg('days', 400));
const sched = buildSchedule(content, { launchDateKey: launch, days, seed: 'kedupan-v1' });
const bad = checkSchedule(content, sched);
if (bad.length) {
  console.error(bad.slice(0, 40).join('\n'));
  process.exit(1);
}
const lines = sched.days.map((d) => "    ['" + d.join("', '") + "'],");
const src =
  '/**\n * GENERATED by tools/build-schedule.js (seed kedupan-v1). Do not edit by hand.\n' +
  ' * Issue N is days[N-1]; issue 1 is launchDateKey (a Beijing date). Item ids refer to spectra.v1.js.\n */\n\n' +
  'module.exports = {\n  scheduleVersion: 1,\n  contentVersion: ' + sched.contentVersion + ",\n  launchDateKey: '" + launch + "',\n  days: [\n" + lines.join('\n') + '\n  ],\n};\n';
fs.writeFileSync(OUT, src);
const used = new Set(sched.days.flat());
console.log('wrote', OUT, days, 'days,', used.size, 'items used of', Object.keys(content.itemById).length);
