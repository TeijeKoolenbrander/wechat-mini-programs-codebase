#!/usr/bin/env node
/**
 * Prints the skeleton of the content review sheet (spec 4.4, AC 10) as markdown, one row per spectrum:
 *   node tools/review-sheet.js > docs/kedupan/content-review.md
 * Author and date are pre-filled (original text written by minigame-dev, 2026-10-15, no external lists consulted);
 * reviewer and result are left for product-ux (every spectrum) and QA (rule check).
 */
const path = require('node:path');
const raw = require(path.join(__dirname, '../core/content/spectra.v1.js'));
const labels = {};
raw.categories.forEach((c) => (labels[c.key] = c.label));

const out = [];
out.push('# 群友刻度盘 content review sheet (content version ' + raw.contentVersion + ')');
out.push('');
out.push('Generated by `apps/kedupan/game/tools/review-sheet.js`. Drafted by the minigame-dev agent (AI-assisted authoring): written from scratch, no other game\'s list was opened, translated or adapted. Per spec 4.4 this text still needs a human review and rewrite pass (product-ux on every spectrum, QA rule check, founder spot check H9) before it ships; reviewer and result are filled in by them.');
out.push('');
out.push('| id | spectrum | category | items | drafted by | date | product-ux review | QA rule check |');
out.push('|---|---|---|---|---|---|---|---|');
raw.spectra.forEach((s) => out.push('| ' + s.id + ' | ' + s.left + ' ↔ ' + s.right + ' | ' + labels[s.cat] + ' | ' + s.items.length + ' | minigame-dev agent (AI-assisted) | 2026-10-15 | pending | pending |'));
process.stdout.write(out.join('\n') + '\n');
