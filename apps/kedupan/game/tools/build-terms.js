'use strict';
/**
 * Generates js/terms-text.js (the 用户协议 shown by the `terms` screen) from docs/kedupan/release/user-agreement.txt.
 *
 *   node tools/build-terms.js             write js/terms-text.js (draft allowed: the 【草稿…】 line and the 【…】 placeholders stay)
 *   node tools/build-terms.js --release   same, but FAIL (exit 1, nothing written) if the draft marker or any 【…】
 *                                         placeholder remains (also KEDUPAN_RELEASE=1)
 *   node tools/build-terms.js --check     write nothing; exit 1 if js/terms-text.js differs from what the source gives
 *
 * Output shape: { title, draft?: '<notice line>', paragraphs: [{ text, important?: true, heading?: true }] }
 *  - one paragraph per non-empty source line (list items "· ..." and "1. ..." included)
 *  - a line that starts with 【重要】 (or "2. 【重要】") is important: the marker is removed from text. "【重要】" inside a
 *    sentence is plain text.
 *  - a line like "一、服务说明" is a heading
 *  - the first line after the draft marker is `title` ("群友刻度盘用户协议"); it is NOT in `paragraphs` (the terms screen draws it)
 *  - the leading 【草稿…】 line is NOT in `paragraphs` either (render/CONTRACT.md); it is kept in the top-level `draft` field
 *    so the release refusal still sees it. Marker convention (TD-95): 【重要】 is stripped and styled via `important`.
 * Every material change to the agreement requires a CLUE_RULES_VERSION bump (js/clue-ui.js RULES_VERSION and the server), see RELEASE.md.
 */
const fs = require('node:fs');
const path = require('node:path');

const GAME = path.join(__dirname, '..');
const SOURCE = path.join(GAME, '..', '..', '..', 'docs', 'kedupan', 'release', 'user-agreement.txt');
const TARGET = path.join(GAME, 'js', 'terms-text.js');

const HEADING = /^[一二三四五六七八九十]+、/;
const IMPORTANT = '【重要】';
const LEAD_IMPORTANT = /^(\d+\.\s*)?【重要】/;
const DRAFT =/^【草稿/;
const PLACEHOLDER = /【[^】]+】/g;

function parse(src) {
  const lines = String(src).replace(/^﻿/, '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  let title = null;
  let draft;
  const paragraphs = [];
  for (const line of lines) {
    if (DRAFT.test(line)) {
      draft = line;
    } else if (title === null) {
      title = line;
    } else if (HEADING.test(line)) {
      paragraphs.push({ text: line, heading: true });
    } else if (LEAD_IMPORTANT.test(line)) {
      // "【重要】text" or "2. 【重要】text": the marker goes, the list number stays
      paragraphs.push({ text: line.replace(IMPORTANT, '').replace(/^(\d+\.)\s+/, '$1 ').trim(), important: true });
    } else {
      paragraphs.push({ text: line });
    }
  }
  return draft ? { title: title || '', draft, paragraphs } : { title: title || '', paragraphs };
}

/** what must be empty in a release: the draft marker and every 【…】 placeholder left in the text */
function releaseProblems(terms) {
  const out = [];
  if (!terms || !terms.title) out.push('no title');
  const all = [(terms && terms.title) || '', (terms && terms.draft) || ''].filter(Boolean).concat(((terms && terms.paragraphs) || []).map((p) => p.text));
  for (const t of all) {
    if (DRAFT.test(t)) {
      out.push('draft marker still present: ' + t.slice(0, 30));
      continue;
    }
    const m = t.replace(/【重要】/g, '').match(PLACEHOLDER);
    if (m) out.push('placeholder ' + m.join(' ') + ' in: ' + t.slice(0, 30));
  }
  return out;
}

function render(terms) {
  return (
    "'use strict';\n" +
    '// GENERATED by tools/build-terms.js from docs/kedupan/release/user-agreement.txt. Do not edit by hand; run `node tools/build-terms.js`.\n' +
    'module.exports = ' + JSON.stringify(terms, null, 2) + ';\n'
  );
}

function build(src) {
  const terms = parse(src);
  return { terms, js: render(terms) };
}

function main(argv) {
  const release = argv.includes('--release') || process.env.KEDUPAN_RELEASE === '1';
  const { terms, js } = build(fs.readFileSync(SOURCE, 'utf8'));
  if (release) {
    const problems = releaseProblems(terms);
    if (problems.length) {
      console.error('build-terms --release FAILED: the agreement is not final:\n  ' + problems.join('\n  '));
      return 1;
    }
  }
  if (argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== js) {
      console.error('js/terms-text.js is out of date: run node tools/build-terms.js');
      return 1;
    }
    return 0;
  }
  fs.writeFileSync(TARGET, js);
  console.log('wrote js/terms-text.js: ' + terms.paragraphs.length + ' paragraphs' + (release ? ' (release checks passed)' : ''));
  return 0;
}

module.exports = { parse, build, render, releaseProblems, SOURCE, TARGET };
if (require.main === module) process.exit(main(process.argv.slice(2)));
