/**
 * Controller: the game's state machine (spec 2, 6). Renderers draw what `view()` returns and report taps / raw ruler
 * touches; ALL logic is here and in js/flows/*. No drawing, no layout, no wx calls except through the injected
 * platform objects, so QA can drive it headless against the mock server.
 *
 * Structure: this file is the kernel (state, navigation, hit routing, ruler input, lifecycle, settings, banner sync);
 * the flows install their handlers on the kernel:
 *   flows/daily.js    home, daily card play, reveal, day result, 加一题, 全国分布, card report
 *   flows/archive.js  往期刻度: list, review, archive play, set end, interstitial
 *   flows/rounds.js   出题 (create), guess / host / reveal, subscribe
 *   flows/boards.js   本群 page and 好友榜 (+ open data domain messaging)
 *   flows/entry.js    card entry routing (spec 7.5), group context (joinGroup), warm start deferral
 *
 * Rules the whole file respects: the device clock is never used for a date (server time + offset); no screen takes
 * typed text; nothing is granted by a share; an ad never changes a score (AC 81).
 */

const VM = require('./vm');
const { createRuler, makeTrack } = require('../core/ruler');
const { beijingDateKey, addDays } = require('../core/date');
const { copyFor, isNetworkError } = require('../core/errors');
const { normalizeFeatures } = require('./features');
const { randomSeed } = require('../core/rng');
const { uuid } = require('./util');
const { createKeyboard } = require('./keyboard');
const TERMS = require('./terms-text'); // generated by tools/build-terms.js from docs/kedupan/release/user-agreement.txt

const TOAST_MS = 2400;

function createController(d) {
  const { wx, api, store, analytics, ads, share, privacy, subscribe, odc, audio, config, content } = d;
  const now = d.now || (() => Date.now());
  const invalidate = d.invalidate || (() => {});
  const keyboard = d.keyboard || createKeyboard(wx);

  const st = {
    screen: 'home',
    offsetMs: 0,
    daily: null,
    dailyStatus: 'loading', // loading | ok | offline | error | unavailable
    features: normalizeFeatures(null),
    group: { status: 'none', groupRef: null, shareTicket: null },
    sheet: null,
    sheetScroll: 0,
    scrollY: 0,
    howtoAuto: false,
    play: null,
    result: null,
    create: null,
    round: null,
    gpage: null,
    boardKind: 'group',
    boardFrom: 'home',
    fpage: null,
    arch: { state: 'loading', items: [], hasMore: false, bestStreak: 0, offline: false, view: 'list', review: { state: 'loading', dateKey: '', data: null }, end: null, sessionSets: 0 },
    adState: { bonus: 'idle', distribution: 'idle', swap: 'idle' },
    dist: {}, // set key -> 5 x 21 histograms (this session)
    toast: null,
    dialog: null,
    nav: 0, // navigation token: async results of a screen the player already left are dropped
    deferred: null,
    sessionSeed: randomSeed(),
  };

  const ruler = createRuler();
  const handlers = Object.create(null);
  const prefixHandlers = [];
  const once = Object.create(null);
  let scrollMax = {};
  let lastHits = null;
  let caretBeat = -1;

  const K = {
    d,
    wx,
    api,
    store,
    analytics,
    ads,
    share,
    privacy,
    subscribe,
    odc,
    audio,
    config,
    content,
    keyboard,
    st,
    ruler,
    invalidate,
    now,
    handlers,
    on(id, fn) {
      handlers[id] = fn;
    },
    onPrefix(prefix, fn) {
      prefixHandlers.push([prefix, fn]);
    },
    srvNow: () => now() + st.offsetMs,
    todayKey: () => beijingDateKey(now() + st.offsetMs),
    track: (name, props) => analytics.track(name, props),
    trackOnce(key, name, props) {
      if (once[key]) return false;
      once[key] = true;
      return analytics.track(name, props);
    },
    toast(text) {
      st.toast = { text, until: now() + TOAST_MS };
      invalidate();
    },
    copy: copyFor,
    isNet: isNetworkError,
    /** Leave the current screen for `screen`; async results of the previous screen are invalidated. */
    go(screen) {
      if (st.screen === 'create' && screen !== 'create' && K.leaveCreate) K.leaveCreate();
      st.nav++;
      st.screen = screen;
      st.scrollY = 0;
      st.sheet = null;
      st.sheetScroll = 0;
      invalidate();
      K.syncBanner();
      return st.nav;
    },
    live: (tok) => tok === st.nav,
    layout: () => d.getLayout(),
  };

  // ---- settings, display, sound -------------------------------------------------------------------------------------

  const display = () => VM.displayOf(store.state.display);
  K.display = display;

  function setDisplay(patch, source) {
    const cur = store.state.display || { largeText: false, highContrast: false };
    store.state.display = Object.assign({}, cur, patch);
    store.save();
    const dsp = store.state.display;
    K.track('display_setting', { largeText: !!dsp.largeText, highContrast: !!dsp.highContrast, source });
    if (d.relayout) d.relayout();
    invalidate();
  }

  function setMuted(m) {
    store.state.muted = !!m;
    audio.setMuted(m);
    store.save();
    invalidate();
  }

  // ---- ad stub overlay + banner ---------------------------------------------------------------------------------------

  K.syncBanner = function syncBanner() {
    if (!ads || !ads.bannerShow) return;
    let v = null;
    try {
      if (st.screen === 'group' && st.boardKind === 'group' && st.gpage) v = VM.groupPage(K.ctx(0));
      else if (st.screen === 'group' && st.boardKind === 'friend' && st.fpage) v = VM.friendBoard(K.ctx(0));
      else if (st.screen === 'archive' && st.arch.view === 'list') v = VM.archiveList(K.ctx(0));
    } catch (e) {
      v = null;
    }
    const f = st.features.banner;
    const show = !!(v && v.banner && v.banner.show && f && f.enabled && f.adUnitId) && !st.sheet && !st.dialog;
    if (show) {
      const L = K.layout();
      const r = d.bannerRect ? d.bannerRect(L, v.banner) : null;
      ads.bannerShow({
        unitId: f.adUnitId,
        left: r ? r.x : L.x0,
        width: r ? r.w : L.contentW,
        bottomEdge: r ? r.y + r.h : L.bottomEdge,
        gap: 24,
      });
    } else if (ads.bannerActive) ads.bannerDestroy();
  };

  // ---- context handed to the vm builders -------------------------------------------------------------------------------

  K.ctx = function ctx(t) {
    return {
      st,
      store,
      features: st.features,
      now: t === 0 ? now() : t || now(),
      srvNow: K.srvNow(),
      todayKey: K.todayKey(),
      launchKey: K.launchKey(),
      ruler,
      bannerHeight: ads ? ads.bannerHeight : 0,
      sharedCanvas: odc ? odc.sharedCanvas() : null,
      keyboardHeight: keyboard.height,
      adOverlay: ads ? ads.overlay : null,
      subscribeState: (roundId) => subscribe.stateFor(st.features, roundId),
    };
  };
  // Launch date for issue numbers. The schedule is server-only (TD-62), so the client never reads it: before the first
  // getDaily it is the config constant; once getDaily has answered it is derived from that answer (dateKey and
  // issueNo), so a LAUNCH_DATE_KEY override on the server is followed without shipping the schedule.
  K.launchKey = () => {
    const daily = st.daily;
    if (daily && /^\d{8}$/.test(daily.dateKey || '') && Number.isInteger(daily.issueNo) && daily.issueNo >= 1) return addDays(daily.dateKey, -(daily.issueNo - 1));
    return d.launchKey || config.daily.launchDateKey;
  };

  // ---- ruler input (core/ruler.js is the only thing that turns touches into positions) --------------------------------------

  function rulerScreen() {
    if (st.screen === 'card' && st.play && (st.play.phase === 'empty' || st.play.phase === 'placing')) return 'card';
    if (st.screen === 'round' && st.round && K.roundPlacing && K.roundPlacing()) return 'round';
    return null;
  }

  function track() {
    if (lastHits && lastHits.ruler) return { x0: lastHits.ruler.x0, x1: lastHits.ruler.x1 };
    return makeTrack({ x: 0, width: K.layout().W });
  }

  function afterRulerChange() {
    const p = st.play;
    if (st.screen === 'card' && p) {
      p.phase = ruler.pos === null ? 'empty' : 'placing';
      if (p.coach) {
        p.coach = false;
        store.state.coachSeen = true;
        store.save();
      }
    }
    if (ruler.consumeTick()) audio.play('tick');
    invalidate();
  }

  K.afterRulerChange = afterRulerChange;

  /** Is a hit id a live ruler band that should receive raw touches? */
  K.isRulerHit = (id) => (id === 'card:ruler' && rulerScreen() === 'card') || (id === 'round:ruler' && rulerScreen() === 'round');

  K.onRulerStart = (touchId, x) => {
    if (!rulerScreen()) return false;
    const moved = ruler.touchStart(touchId, x, track(), now());
    if (moved) afterRulerChange();
    return true;
  };
  K.onRulerMove = (touchId, x) => {
    if (ruler.touchMove(touchId, x, track())) afterRulerChange();
  };
  K.onRulerEnd = (touchId) => ruler.touchEnd(touchId);
  K.onRulerCancel = (touchId) => ruler.touchCancel(touchId);
  K.nudge = (dir) => {
    if (!rulerScreen()) return;
    if (ruler.nudge(dir)) afterRulerChange();
  };
  K.on('card:nudgeL', () => K.nudge(-1));
  K.on('card:nudgeR', () => K.nudge(1));
  K.on('round:nudgeL', () => K.nudge(-1));
  K.on('round:nudgeR', () => K.nudge(1));
  K.on('card:ruler', () => {}); // a tap on the band without a drag already moved the needle at touchstart
  K.on('round:ruler', () => {});

  // ---- sheets, scrolling ------------------------------------------------------------------------------------------------------

  K.on('sheet:close', () => {
    if (st.screen === 'create' && K.closeCreateSheet && K.closeCreateSheet()) return;
    if (st.sheet === 'rules') {
      st.sheet = 'settings';
      st.sheetScroll = 0;
      return;
    }
    if (st.sheet) {
      st.sheet = null;
      st.sheetScroll = 0;
      invalidate();
      K.syncBanner();
    }
  });
  K.on('sheet:list', () => {});
  K.on('sheet:body', () => {});
  K.on('sheet:scrim', () => {
    if (st.sheet) K.handlers['sheet:close']();
  });
  K.on('coach:block', () => {});
  K.on('dialog:block', () => {});
  K.on('adstub:block', () => {});

  K.setScrollMax = (m) => {
    scrollMax = m || {};
  };
  K.setHits = (h) => {
    lastHits = h;
  };

  /** A vertical drag of `dy` px on the scroll region `id` (finger down = content down). */
  K.onDrag = function onDrag(id, dy) {
    const max = scrollMax[id] === undefined ? 0 : scrollMax[id];
    const clampv = (v) => Math.max(0, Math.min(max, v));
    if (id === 'sheet:list') st.sheetScroll = clampv(st.sheetScroll - dy);
    else if (id === 'board:list' || id === 'round:list') {
      const key = id === 'round:list' ? 'listScroll' : 'listScroll';
      const holder = id === 'round:list' ? st.round : st.boardKind === 'friend' ? st.fpage : st.gpage;
      if (holder) {
        holder[key] = Math.max(0, Math.min(max, (holder[key] || 0) - dy));
        if (odc) odc.scroll(holder[key]);
      }
    } else st.scrollY = clampv(st.scrollY - dy);
    invalidate();
  };

  // ---- hit routing ---------------------------------------------------------------------------------------------------------------

  /** Is this hit id routed by logic (or a tap-swallowing id)? Used by the integration test against the real renderers. */
  K.hasHandler = (id) => !!handlers[id] || prefixHandlers.some((ph) => id.indexOf(ph[0]) === 0);

  K.onHit = function onHit(id) {
    if (st.dialog && id !== 'dialog:confirm' && id !== 'dialog:cancel') return;
    if (ads && ads.overlay) {
      if (id === 'adstub:complete') ads.stubComplete(true);
      else if (id === 'adstub:skip') ads.stubSkip();
      return;
    }
    const fn = handlers[id];
    if (fn) {
      fn(id);
      invalidate();
      return;
    }
    for (let i = 0; i < prefixHandlers.length; i++) {
      const [pre, h] = prefixHandlers[i];
      if (id.indexOf(pre) === 0) {
        h(id.slice(pre.length), id);
        invalidate();
        return;
      }
    }
  };

  K.on('dialog:confirm', () => {
    const dlg = st.dialog;
    st.dialog = null;
    if (dlg && dlg.onConfirm) dlg.onConfirm();
  });
  K.on('dialog:cancel', () => {
    const dlg = st.dialog;
    st.dialog = null;
    if (dlg && dlg.onCancel) dlg.onCancel();
  });

  // ---- install flows ---------------------------------------------------------------------------------------------------------------

  require('./flows/daily')(K);
  require('./flows/archive')(K);
  require('./flows/rounds')(K);
  require('./flows/boards')(K);
  require('./flows/entry')(K);

  // ---- home sheets / settings -------------------------------------------------------------------------------------------------

  K.on('home:howto', () => {
    st.sheet = 'howto';
    st.howtoAuto = false;
    st.sheetScroll = 0;
    K.track('howto_view', { auto: false });
  });
  K.on('home:settings', () => {
    st.sheet = 'settings';
    st.sheetScroll = 0;
  });
  K.on('home:sound', () => setMuted(!store.state.muted));
  K.on('settings:sound', () => setMuted(!store.state.muted));
  K.on('settings:largeText', () => setDisplay({ largeText: !display().largeText }, 'settings'));
  K.on('settings:highContrast', () => setDisplay({ highContrast: !display().highContrast }, 'settings'));
  K.on('settings:openSetting', () => {
    privacy.openSetting().then(() => invalidate());
  });
  K.on('settings:privacy', () => {
    if (wx.openPrivacyContract) wx.openPrivacyContract({ success() {}, fail() {} });
  });
  K.on('settings:feedback', () => {}); // the native feedback button sits over this rect (main.js)
  // 《用户协议》: a scrollable text screen opened from 设置 and from the 发言规则 sheet. It is entered WITHOUT K.go so the sheet or the
  // typed draft underneath survives; 返回 restores the screen and its scroll.
  function showTerms() {
    if (st.screen === 'terms') return;
    K.closeKeyboard();
    st.termsReturn = { screen: st.screen, scrollY: st.scrollY };
    st.screen = 'terms';
    st.scrollY = 0;
  }
  K.on('settings:terms', showTerms);
  K.on('rules:terms', showTerms);
  K.on('terms:back', () => {
    const r = st.termsReturn || { screen: 'home', scrollY: 0 };
    st.termsReturn = null;
    st.screen = r.screen;
    st.scrollY = r.scrollY;
  });
  K.on('terms:scroll', () => {});
  K.on('settings:rules', () => {
    st.sheet = 'rules'; // 发言规则, read-only (spec 6.12)
    st.sheetScroll = 0;
    K.track('rules_view', { source: 'settings' });
  });
  K.on('home:scroll', () => {});
  ['card', 'create', 'board', 'round', 'result', 'review'].forEach((p) => K.on(p + ':scroll', () => {}));
  ['clueReport:block', 'rules:block', 'warn:block'].forEach((id) => K.on(id, () => {}));

  // ---- navigation helpers used by several flows ------------------------------------------------------------------------------

  K.goHome = function goHome() {
    K.go('home');
    st.play = null;
    ruler.reset();
    K.loadDaily();
    K.resumeDeferred();
    invalidate();
  };

  // ---- public API --------------------------------------------------------------------------------------------------------------------

  const ctl = {
    K,
    st,
    ruler,
    start(options) {
      const first = store.state.firstDate === null;
      if (!store.state.installId) store.state.installId = uuid();
      if (first) store.state.firstDate = beijingDateKey(now());
      store.state.lastSessionAt = now();
      store.save();
      share.register(() => ({}));
      K.startEntry(options);
      if (!store.state.howtoSeen) {
        st.sheet = 'howto';
        st.howtoAuto = true;
        store.state.howtoSeen = true;
        store.save();
        K.track('howto_view', { auto: true });
      }
      analytics.startTimer();
      return K.loadDaily().then(() => K.afterLaunchLoad());
    },
    onShow(options) {
      K.onAppVisibility(); // the typing keyboard is closed on return, the draft stays in the box
      if (d.relayout) d.relayout();
      K.onShowEntry(options);
      privacy.refreshOnShow().then(() => K.afterPrivacyChange());
      if (st.screen === 'home' || st.screen === 'result') {
        K.loadDaily().then(() => {
          K.afterLaunchLoad();
          if (st.screen === 'result') K.refreshResult();
        });
      }
      invalidate();
    },
    onHide() {
      K.onAppVisibility();
      analytics.onHide();
      store.save();
    },
    /** The frame's content: { screen, vm, overlay }. */
    view(t) {
      const c = K.ctx(t);
      let vm;
      switch (st.screen) {
        case 'home':
          vm = VM.home(c);
          break;
        case 'card':
          vm = VM.card(c);
          break;
        case 'result':
          vm = VM.result(c);
          break;
        case 'create':
          vm = VM.create(c);
          break;
        case 'round':
          vm = VM.round(c);
          break;
        case 'group':
          vm = st.boardKind === 'friend' ? VM.friendBoard(c) : VM.groupPage(c);
          break;
        case 'archive':
          vm = VM.archive(c);
          break;
        case 'terms':
          vm = VM.terms(c, TERMS);
          break;
        default:
          vm = VM.home(c);
      }
      return { screen: st.screen, vm, overlay: VM.overlay(c) };
    },
    /** Keep redrawing while something moves (reveal slide, confetti, stub ad countdown). */
    animating(t) {
      const tt = t || now();
      if (ads && ads.overlay) return true;
      if (st.toast && tt < st.toast.until) return true;
      if (st.screen === 'card' && st.play) {
        const p = st.play;
        if (p.phase === 'revealed' && (tt - p.revealAt < VM.REVEAL_MS || (p.confetti && tt - p.confetti.t0 < VM.CONFETTI_MS))) return true;
      }
      if (st.screen === 'round' && st.round && st.round.revealAt && tt - st.round.revealAt < VM.REVEAL_MS) return true;
      if (st.screen === 'result' && st.result && tt - (st.result.enteredAt || 0) < 800) return true;
      if (st.sheet === 'howto') return true; // the small animated ruler
      if (st.screen === 'create' && st.create && st.create.kbOpen) {
        const beat = Math.floor(tt / 500); // the caret blinks: one redraw per half second
        if (beat !== caretBeat) {
          caretBeat = beat;
          return true;
        }
      }
      return false;
    },
    onHit: K.onHit,
    onDrag: K.onDrag,
    setScrollMax: K.setScrollMax,
    setHits: K.setHits,
    isRulerHit: K.isRulerHit,
    onRulerStart: K.onRulerStart,
    onRulerMove: K.onRulerMove,
    onRulerEnd: K.onRulerEnd,
    onRulerCancel: K.onRulerCancel,
    display,
  };
  return ctl;
}

module.exports = { createController };
